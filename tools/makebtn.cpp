// Renders the three small job-queue button icons (stop, trash bin, repeat) into src/qicons.h.
// Same method as the app icon (tools/makeicon.cpp): signed shapes sampled with 6x6 supersampling, so the edges are smooth at 18 x 18 pixels.
// Build: g++ -O2 tools/makebtn.cpp -o build/makebtn.exe && build/makebtn.exe src/qicons.h
#include <cmath>
#include <cstdint>
#include <cstdio>
using namespace std;

struct C { float r, g, b, a; };
static C over(C d, C s) { float a = s.a + d.a * (1 - s.a); if (a <= 0) return {0, 0, 0, 0};
    return {(s.r * s.a + d.r * d.a * (1 - s.a)) / a, (s.g * s.a + d.g * d.a * (1 - s.a)) / a, (s.b * s.a + d.b * d.a * (1 - s.a)) / a, a}; }
static bool inRR(float x, float y, float x0, float y0, float x1, float y1, float r) {
    if (x < x0 || x > x1 || y < y0 || y > y1) return false;
    float cx = x < x0 + r ? x0 + r : (x > x1 - r ? x1 - r : x), cy = y < y0 + r ? y0 + r : (y > y1 - r ? y1 - r : y);
    return (x - cx) * (x - cx) + (y - cy) * (y - cy) <= r * r;
}
static bool inTri(float px, float py, float ax, float ay, float bx, float by, float cx, float cy) {
    auto s = [](float x1, float y1, float x2, float y2, float x3, float y3) { return (x1 - x3) * (y2 - y3) - (x2 - x3) * (y1 - y3); };
    const float d1 = s(px, py, ax, ay, bx, by), d2 = s(px, py, bx, by, cx, cy), d3 = s(px, py, cx, cy, ax, ay);
    return !(((d1 < 0) || (d2 < 0) || (d3 < 0)) && ((d1 > 0) || (d2 > 0) || (d3 > 0)));
}

// glyph: is the point (u, v) in 0..1 part of the white drawing?
static bool glyph(int kind, float u, float v) {
    if (kind == 0) return inRR(u, v, 0.29f, 0.29f, 0.71f, 0.71f, 0.06f);                                  // stop: a rounded square
    if (kind == 1) {                                                                                       // trash bin
        if (inRR(u, v, 0.20f, 0.25f, 0.80f, 0.33f, 0.03f)) return true;                                    // lid
        if (inRR(u, v, 0.38f, 0.17f, 0.62f, 0.27f, 0.03f) && !inRR(u, v, 0.44f, 0.22f, 0.56f, 0.30f, 0.0f)) return true;   // handle
        const float t = (v - 0.37f) / (0.84f - 0.37f);                                                     // body: narrows towards the bottom
        if (v >= 0.37f && v <= 0.84f) {
            const float l = 0.26f + 0.04f * t, r = 0.74f - 0.04f * t;
            if (u >= l && u <= r) { const bool slit = v > 0.45f && v < 0.74f && (fabsf(u - 0.40f) < 0.025f || fabsf(u - 0.50f) < 0.025f || fabsf(u - 0.60f) < 0.025f); return !slit; }
        }
        return false;
    }
    {                                                                                                      // repeat: a ring open at the top right, with an arrow head
        const float dx = u - 0.5f, dy = v - 0.52f, r = sqrtf(dx * dx + dy * dy); float th = atan2f(-dy, dx) * 57.29578f; if (th < 0) th += 360;   // degrees, counter-clockwise from the right
        if (r > 0.17f && r < 0.27f && !(th > 15 && th < 70)) return true;
        const float ex = 0.5f + 0.22f * cosf(15 * 0.0174533f), ey = 0.52f - 0.22f * sinf(15 * 0.0174533f);  // end of the ring at 15 degrees: the head points clockwise (downwards there)
        return inTri(u, v, ex + 0.11f, ey - 0.01f, ex - 0.11f, ey - 0.01f, ex, ey - 0.15f + 0.0f) || inTri(u, v, ex + 0.12f, ey + 0.0f, ex - 0.10f, ey + 0.0f, ex + 0.01f, ey + 0.13f);
    }
}

int main(int argc, char** argv) {
    const int S = 18, SS = 6; const float base[3][3] = {{0.80f, 0.55f, 0.12f}, {0.80f, 0.20f, 0.20f}, {0.20f, 0.60f, 0.32f}};   // amber, red, green
    FILE* f = fopen(argc > 1 ? argv[1] : "qicons.h", "w"); if (!f) return 1;
    fprintf(f, "// Generated by tools/makebtn.cpp: the job-queue button icons, 18 x 18, 0x00RRGGBB, row by row from the top. Stop, trash bin, repeat.\n#pragma once\n#include <cstdint>\nstatic const int kQIconSize = %d;\nstatic const uint32_t kQIcons[3][%d] = {\n", S, S * S);
    for (int k = 0; k < 3; k++) {
        fprintf(f, "{");
        for (int y = 0; y < S; y++) for (int x = 0; x < S; x++) {
            float r = 0, g = 0, b = 0;
            for (int j = 0; j < SS; j++) for (int i = 0; i < SS; i++) {
                const float u = (x + (i + 0.5f) / SS) / S, v = (y + (j + 0.5f) / SS) / S;
                C c = {base[k][0] * (0.85f + 0.3f * (1 - v)), base[k][1] * (0.85f + 0.3f * (1 - v)), base[k][2] * (0.85f + 0.3f * (1 - v)), 1};     // the button: a soft vertical gradient
                if (glyph(k, u, v)) c = {1, 1, 1, 1};
                r += c.r; g += c.g; b += c.b;
            }
            const float inv = 1.0f / (SS * SS); auto q = [&](float t) { int n = (int)(t * inv * 255 + 0.5f); return n > 255 ? 255 : n; };
            fprintf(f, "%s0x%02X%02X%02X", (x || y) ? "," : "", q(r), q(g), q(b));
            if ((y * S + x) % 9 == 8) fprintf(f, "\n");
        }
        fprintf(f, "}%s\n", k < 2 ? "," : "");
    }
    fprintf(f, "};\n"); fclose(f);
    return 0;
}
